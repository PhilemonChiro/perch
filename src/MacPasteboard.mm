#include "MacPasteboard.h"

#import <AppKit/AppKit.h>

namespace MacPasteboard {

bool isConcealed()
{
    @autoreleasepool {
        NSArray<NSPasteboardType>* types = [[NSPasteboard generalPasteboard] types];
        for (NSString* t in @[ @"org.nspasteboard.ConcealedType", @"org.nspasteboard.TransientType",
                               @"org.nspasteboard.AutoGeneratedType" ])
            if ([types containsObject:t])
                return true;
        return false;
    }
}

bool reduceMotion()
{
    return [[NSWorkspace sharedWorkspace] accessibilityDisplayShouldReduceMotion];
}

void revealInFinder(const QStringList& paths)
{
    @autoreleasepool {
        NSMutableArray<NSURL*>* urls = [NSMutableArray arrayWithCapacity:NSUInteger(paths.size())];
        for (const QString& p : paths)
            [urls addObject:[NSURL fileURLWithPath:p.toNSString()]];
        [[NSWorkspace sharedWorkspace] activateFileViewerSelectingURLs:urls];
    }
}

} // namespace MacPasteboard
